import re
import shutil
import subprocess
import time
from pathlib import Path

import numpy as np
from scipy import signal
import soundfile as sf
import pyloudnorm as pyln

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
JAVA = REPO / "mobile/src/main/java/com/bayapps/android/robophish/audio/offline"
BANDS = [("sub", 0, 35), ("bass", 35, 160), ("low_mid", 160, 500), ("mid", 500, 2000), ("presence", 2000, 6000), ("air", 6000, 16000), ("upper", 16000, 24000)]


def run(args, **kwargs):
    return subprocess.run([str(a) for a in args], check=True, **kwargs)


def db(value):
    return 20 * math.log10(max(float(value), 1e-15))


def file_hash(path):
    with Path(path).open("rb") as file:
        return hashlib.file_digest(file,"sha256").hexdigest()


def cached_original_metrics(path,rate,channels,cache):
    cache.mkdir(exist_ok=True)
    key=hashlib.sha256((file_hash(path)+str(rate)+str(channels)+inspect.getsource(metrics)+inspect.getsource(ebur128)).encode()).hexdigest()
    metadata=cache/(key+".json")
    arrays=cache/(key+".npz")
    if metadata.exists() and arrays.exists():
        with np.load(arrays) as values:
            print("ORIGINAL_METRICS_CACHE",Path(path).name,flush=True)
            return json.loads(metadata.read_text()),values["envelope"],values["onset_flux"]
    measured,envelope,flux=metrics(path,rate,channels)
    metadata.write_text(json.dumps(measured,indent=2)+"\n")
    np.savez_compressed(arrays,envelope=envelope,onset_flux=flux)
    return measured,envelope,flux


def fingerprint():
    files = [JAVA / "OfflineRestorationProfile.java", JAVA / "OfflineRestorationDsp.java", ROOT / "OfflineRender.java"]
    return {str(p.relative_to(REPO)): hashlib.sha256(p.read_bytes()).hexdigest() for p in files}


def protocol_fingerprint():
    return {p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [ROOT/"evaluate.py",ROOT/"manifest.json"]}


def compile_java(out):
    out.mkdir(exist_ok=True)
    java_home = Path("/Applications/Android Studio.app/Contents/jbr/Contents/Home/bin")
    javac = str(java_home / "javac") if (java_home / "javac").exists() else "javac"
    sources=out/"source-snapshot"
    sources.mkdir(exist_ok=True)
    snapshot=[]
    hashes={}
    for source in [JAVA/"OfflineRestorationProfile.java",JAVA/"OfflineRestorationDsp.java",ROOT/"OfflineRender.java"]:
        content=source.read_bytes()
        copied=sources/source.name
        copied.write_bytes(content)
        snapshot.append(copied)
        hashes[str(source.relative_to(REPO))]=hashlib.sha256(content).hexdigest()
    (out/"source-fingerprint.json").write_text(json.dumps(hashes,indent=2)+"\n")
    run([javac, "-d", out, *snapshot])
    return str(java_home / "java") if (java_home / "java").exists() else "java"


def decode(source, target, rate, channels):
    run(["ffmpeg", "-v", "error", "-y", "-i", source, "-map", "0:a:0", "-ar", rate, "-ac", channels, "-c:a", "pcm_s16le", "-f", "s16le", target])


def ebur128(path, rate, channels):
    result = run(["ffmpeg", "-hide_banner", "-nostats", "-f", "s16le", "-ar", rate, "-ac", channels, "-i", path, "-af", "ebur128=peak=true", "-f", "null", "-"], stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
    summary = result.stderr.rsplit("Summary:", 1)[-1]
    def value(label):
        match = re.search(label + r"\s*:\s*([-+\d.]+)", summary)
        if not match:
            raise RuntimeError("Could not parse ebur128 summary: " + summary)
        return float(match.group(1))
    return {"integrated_lufs": value("I"), "loudness_range_lu": value("LRA"), "ffmpeg_true_peak_dbtp": value("Peak")}


def metrics(path, rate, channels):
    stage_start=time.monotonic()
    x = np.memmap(path, dtype="<i2", mode="r").reshape(-1, channels)
    n = len(x)
    square = np.zeros(channels)
    totals = np.zeros(channels)
    cross = 0.0
    mid_power = side_power = 0.0
    peak = oversampled_peak = 0.0
    clipped = 0
    # Overlapping padding avoids artificial block-boundary oversampling peaks.
    for start in range(0, n, 262144):
        end = min(n, start + 262144)
        y = np.asarray(x[start:end], dtype=np.float64) / 32768
        square += np.sum(y * y, axis=0)
        totals += np.sum(y, axis=0)
        peak = max(peak, float(np.max(np.abs(y))))
        clipped += int(np.count_nonzero(np.abs(y) >= 32767 / 32768))
        if channels == 2:
            cross += float(np.sum(y[:, 0] * y[:, 1]))
            mid_power += float(np.sum(((y[:, 0] + y[:, 1]) / 2) ** 2))
            side_power += float(np.sum(((y[:, 0] - y[:, 1]) / 2) ** 2))
        lo, hi = max(0, start - 64), min(n, end + 64)
        padded = np.asarray(x[lo:hi], dtype=np.float64) / 32768
        up = signal.resample_poly(padded, 4, 1, axis=0)
        core = up[(start-lo)*4:(end-lo)*4]
        oversampled_peak = max(oversampled_peak, float(np.max(np.abs(core))))
    rms = math.sqrt(float(np.sum(square) / (n * channels)))
    print("PCM_METRICS",Path(path).name,round(time.monotonic()-stage_start,2),"seconds",flush=True)
    if channels == 2:
        covariance = cross - totals[0] * totals[1] / n
        correlation = float(covariance / math.sqrt(max((square[0] - totals[0]**2/n) * (square[1] - totals[1]**2/n), 1e-30)))
        side_mid_db = 10 * math.log10(max(side_power, 1e-30) / max(mid_power, 1e-30))
    else:
        correlation, side_mid_db = 1.0, -300.0
    size, hop = 4096, 2048
    window = np.hanning(size)
    spectral_power = np.zeros((channels, size//2+1))
    cross_spectrum = np.zeros(size//2+1, dtype=np.complex128)
    envelope, onset_flux = [], []
    previous_mag = None
    window_count = 0
    for start in range(0, max(n-size+1, 1), hop * 128):
        end = min(n, start + hop*127 + size)
        chunk = np.asarray(x[start:end], dtype=np.float64) / 32768
        if len(chunk) < size:
            continue
        frames = np.lib.stride_tricks.sliding_window_view(chunk, size, axis=0)[::hop]
        z = np.fft.rfft(frames * window, axis=-1)
        power = np.abs(z)**2
        spectral_power += power.sum(axis=0)
        if channels == 2:
            cross_spectrum += (z[:,0] * z[:,1].conj()).sum(axis=0)
        mag = np.sqrt(power.mean(axis=1))
        preceding = np.vstack([previous_mag if previous_mag is not None else mag[0], mag[:-1]])
        onset_flux.extend(np.maximum(mag - preceding, 0).sum(axis=1).tolist())
        previous_mag = mag[-1]
        envelope.extend(np.sqrt(np.mean(frames**2, axis=(1,2))).tolist())
        window_count += len(frames)
    frequency = np.fft.rfftfreq(size, 1/rate)
    bands = {}
    coherence = np.abs(cross_spectrum)**2 / np.maximum(spectral_power[0] * spectral_power[-1], 1e-30)
    for name, low, high in BANDS:
        mask = (frequency >= low) & (frequency < min(high, rate / 2))
        power = float(np.sum(spectral_power[:,mask])) / max(window_count, 1)
        bands[name] = {"power": power, "mean_magnitude_squared_coherence": float(np.mean(coherence[mask])) if channels == 2 and np.any(mask) else None}
    print("SPECTRUM_METRICS",Path(path).name,round(time.monotonic()-stage_start,2),"seconds",flush=True)
    return {"frames": n, "duration_seconds": n/rate, "sample_peak_dbfs": db(peak), "oversampled_peak_estimate_dbfs": db(oversampled_peak), "rms_dbfs": db(rms), "crest_db": db(peak/rms) if rms else 0.0, "stereo_correlation": correlation, "side_mid_db": side_mid_db, "clip_fraction": clipped/(n*channels), "bands": bands, **ebur128(path, rate, channels)}, np.asarray(envelope), np.asarray(onset_flux)


def compare(original, enhanced, original_env, enhanced_env, original_flux, enhanced_flux, passthrough=False):
    gain_db = original["integrated_lufs"] - enhanced["integrated_lufs"]
    gain = 10**(gain_db/20)
    difference = {"loudness_match_gain_db": gain_db, "loudness_change_lu": -gain_db, "crest_change_db": enhanced["crest_db"]-original["crest_db"], "lra_change_lu": enhanced["loudness_range_lu"]-original["loudness_range_lu"], "stereo_correlation_change": enhanced["stereo_correlation"]-original["stereo_correlation"], "side_mid_change_db": enhanced["side_mid_db"]-original["side_mid_db"], "frame_count_equal": original["frames"] == enhanced["frames"]}
    difference["raw_side_mid_change_db"] = difference["side_mid_change_db"]
    difference["near_mono_both"] = original["side_mid_db"] < -60 and enhanced["side_mid_db"] < -60
    if difference["near_mono_both"]:
        # A ratio of effectively absent side-channel energy is ill-conditioned.
        # Preserve its raw value, but test that both remain below a -60dB floor.
        difference["side_mid_change_db"] = 0.0
    if len(original_env) != len(enhanced_env):
        raise RuntimeError("Analysis envelope length differs")
    difference["envelope_correlation"] = float(np.corrcoef(original_env, enhanced_env)[0,1])
    difference["onset_flux_correlation"] = float(np.corrcoef(original_flux, enhanced_flux)[0,1])
    # This is low-level passage preservation, not semantic crowd recognition.
    quiet = (original_env <= np.quantile(original_env, .2)) & (original_env > 1e-5)
    delta = 20*np.log10(np.maximum(enhanced_env*gain,1e-15)/np.maximum(original_env,1e-15))
    difference["low_level_passage_gain_median_db"] = float(np.median(delta[quiet])) if np.any(quiet) else None
    difference["low_level_passage_gain_p05_db"] = float(np.quantile(delta[quiet],.05)) if np.any(quiet) else None
    difference["band_power_change_db_matched"] = {name: 10*math.log10(max(enhanced["bands"][name]["power"],1e-30)/max(original["bands"][name]["power"],1e-30))+gain_db for name,_,_ in BANDS}
    difference["band_coherence_change"] = {name: enhanced["bands"][name]["mean_magnitude_squared_coherence"]-original["bands"][name]["mean_magnitude_squared_coherence"] for name,_,_ in BANDS if original["bands"][name]["mean_magnitude_squared_coherence"] is not None}
    checks = {"same_frame_count": difference["frame_count_equal"], "no_new_integer_clipping": enhanced["clip_fraction"] <= original["clip_fraction"] if passthrough else enhanced["clip_fraction"] == 0, "peak_margin_or_bit_exact_abstention": passthrough or enhanced["oversampled_peak_estimate_dbfs"] <= -.5, "crest_preservation": abs(difference["crest_change_db"]) <= 1.5, "stereo_correlation": abs(difference["stereo_correlation_change"]) <= .05, "stereo_width": abs(difference["side_mid_change_db"]) <= .5, "envelope": difference["envelope_correlation"] >= .98, "onsets": difference["onset_flux_correlation"] >= .95, "low_level_passages": difference["low_level_passage_gain_p05_db"] is None or difference["low_level_passage_gain_p05_db"] >= -1.5}
    checks = {key:bool(value) for key,value in checks.items()}
    difference["provisional_checks"] = checks
    difference["all_preservation_checks_pass"] = all(checks.values())
    return difference


def listening_pair(original_path, enhanced_path, metadata, rate, channels, out):
    original = np.memmap(original_path, dtype="<i2", mode="r").reshape(-1, channels)
    enhanced = np.memmap(enhanced_path, dtype="<i2", mode="r").reshape(-1, channels)
    duration = len(original)/rate
    rows, key = [], []
    # Fixed positions include first/last passages; do not call them crowd-only.
    for label, start in [("opening", 0), ("middle", duration*.5), ("late", duration*.8), ("ending", max(0,duration-12))]:
        start = max(0, min(start, duration-12))
        a = np.asarray(original[int(start*rate):int((start+12)*rate)], dtype=np.float64)/32768
        b = np.asarray(enhanced[int(start*rate):int((start+12)*rate)], dtype=np.float64)/32768
        meter = pyln.Meter(rate)
        la, lb = meter.integrated_loudness(a), meter.integrated_loudness(b)
        if not np.isfinite(la) or not np.isfinite(lb):
            continue
        target = min(la,lb,-18)
        a *= 10**((target-la)/20)
        b *= 10**((target-lb)/20)
        peak = max(np.max(np.abs(signal.resample_poly(a,4,1,axis=0))), np.max(np.abs(signal.resample_poly(b,4,1,axis=0))))
        attenuation = min(1, 10**(-1/20)/max(peak,1e-15))
        a *= attenuation; b *= attenuation
        identity = metadata["date"] + "_" + label
        swap = int(hashlib.sha256((identity+"blind-seed-v1").encode()).hexdigest(),16)%2 == 1
        pair = [b,a] if swap else [a,b]
        files = []
        for variant, audio in zip(["A","B"],pair):
            filename = identity+"_"+variant+".flac"
            sf.write(out/filename, audio, rate, format="FLAC", subtype="PCM_16")
            files.append(filename)
        rows.append(dict(id=identity,date=metadata["date"],title=metadata["title"],passage=label,start_seconds=round(start,3),split=metadata["split"],files=files,loudness_match_error_lu=float(meter.integrated_loudness(a)-meter.integrated_loudness(b)),crowd_annotation="Unreviewed; opening/ending is not assumed to be crowd-only"))
        key.append(dict(id=identity,A="enhanced" if swap else "original",B="original" if swap else "enhanced"))
    return rows,key


def make_page(destination, trials):
    template = (ROOT/"listening.html").read_text()
    (destination/"index.html").write_text(template.replace("__TRIALS_JSON__", json.dumps(trials).replace("</", "<\\/")))


def summarize(rows):
    processed=[r for r in rows if not r["engine"]["profile"]["passthrough"]]
    return dict(recordings=len(rows),full_track_audio_hours=sum(r["original"]["duration_seconds"] for r in rows)/3600,abstentions=len(rows)-len(processed),processed=len(processed),maximum_static_correction_db=max(r["engine"]["profile"]["maximumCorrectionDb"] for r in rows),maximum_dynamic_correction_db=max(r["engine"]["maximum_dynamic_reduction_db"] for r in rows),checks_passed=sum(r["comparison"]["all_preservation_checks_pass"] for r in rows),failed={r["metadata"]["date"]:[k for k,v in r["comparison"]["provisional_checks"].items() if not v] for r in rows if not r["comparison"]["all_preservation_checks_pass"]},median_loudness_change_lu=float(np.median([r["comparison"]["loudness_change_lu"] for r in rows])),max_abs_crest_change_db=max(abs(r["comparison"]["crest_change_db"]) for r in rows),max_abs_stereo_correlation_change=max(abs(r["comparison"]["stereo_correlation_change"]) for r in rows),max_abs_stereo_width_change_db=max(abs(r["comparison"]["side_mid_change_db"]) for r in rows),minimum_onset_flux_correlation=min(r["comparison"]["onset_flux_correlation"] for r in rows),max_oversampled_peak_dbfs=max(r["enhanced"]["oversampled_peak_estimate_dbfs"] for r in rows),max_processed_oversampled_peak_dbfs=max((r["enhanced"]["oversampled_peak_estimate_dbfs"] for r in processed),default=None),subjective_ratings_collected=0,interpretation="Preservation checks are provisional engineering bounds, not an audio quality score or evidence of soundboard equivalence.")


def refresh_preservation_report(path):
    """Apply pre-holdout near-mono metric correction without rerendering audio."""
    data=json.loads(path.read_text())
    for row in data["tracks"]:
        diff=row["comparison"]
        diff["raw_side_mid_change_db"]=row["enhanced"]["side_mid_db"]-row["original"]["side_mid_db"]
        diff["near_mono_both"]=row["original"]["side_mid_db"] < -60 and row["enhanced"]["side_mid_db"] < -60
        diff["side_mid_change_db"]=0.0 if diff["near_mono_both"] else diff["raw_side_mid_change_db"]
        diff["provisional_checks"]["stereo_width"]=abs(diff["side_mid_change_db"])<=.5
        diff["all_preservation_checks_pass"]=all(diff["provisional_checks"].values())
        (path.parent/(row["metadata"]["date"]+"-metrics.json")).write_text(json.dumps(row,indent=2)+"\n")
    data["summary"]=summarize(data["tracks"])
    data["measurement_revision"]="Near-mono width ratio is inapplicable only when both side/mid values are below -60dB; raw value retained. Corrected before holdout inspection."
    path.write_text(json.dumps(data,indent=2)+"\n")
    return data


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--split", choices=["development","holdout"], default="development")
    parser.add_argument("--date", help="Only one development date for iteration")
    parser.add_argument("--freeze", action="store_true", help="Freeze exact core after all16 development results")
    parser.add_argument("--keep-full-wav", action="store_true")
    args=parser.parse_args()
    args.output.mkdir(parents=True,exist_ok=True)
    classes=args.output/"classes"
    current=fingerprint()
    frozen=ROOT/"frozen-protocol.json"
    if args.split=="holdout":
        if not frozen.exists() or json.loads(frozen.read_text())["core_fingerprint"]!=current or json.loads(frozen.read_text()).get("protocol_fingerprint")!=protocol_fingerprint():
            raise RuntimeError("Holdout requires a matching frozen algorithm fingerprint")
        if args.date:
            raise RuntimeError("Do not cherry-pick holdout tracks")
    java=compile_java(classes)
    compiled=json.loads((classes/"source-fingerprint.json").read_text())
    if compiled!=current:
        raise RuntimeError("Core changed during compilation; restart with stable source")
    acquisition=json.loads((ROOT/"acquisition.json").read_text())
    if not acquisition["complete"]:
        raise RuntimeError("Acquisition is incomplete")
    selected=[r for r in acquisition["tracks"] if r["split"]==args.split and (not args.date or r["date"]==args.date)]
    if not selected:
        raise RuntimeError("No selected tracks")
    listening=args.output/"listening"
    listening.mkdir(exist_ok=True)
    rows,trials,answer_key=[],[],[]
    for metadata in selected:
        if (args.output/"STOP_AFTER_TRACK").exists():
            print("STOP_REQUESTED: completed results preserved",flush=True)
            break
        date=metadata["date"]
        rate,channels=metadata["sample_rate"],metadata["channels"]
        source=args.cache/(date+".mp3")
        original=args.output/(date+"-original.s16")
        enhanced=args.output/(date+"-enhanced.s16")
        engine_report=args.output/(date+"-engine.json")
        print("DECODE",date,metadata["split"],flush=True)
        decode(source,original,rate,channels)
        print("RENDER",date,flush=True)
        run([java,"-Xmx512m","-cp",classes,"OfflineRender",original,enhanced,engine_report,rate,channels], stdout=subprocess.DEVNULL)
        print("MEASURE",date,flush=True)
        engine=json.loads(engine_report.read_text())
        passthrough=engine["profile"]["passthrough"]
        if passthrough and file_hash(original)!=file_hash(enhanced):
            raise RuntimeError("Abstained render changed original samples")
        a,ae,af=cached_original_metrics(original,rate,channels,args.cache/"metric-cache")
        b,be,bf=(a,ae,af) if passthrough else metrics(enhanced,rate,channels)
        comparison=compare(a,b,ae,be,af,bf,passthrough)
        row=dict(metadata=metadata,engine=engine,original=a,enhanced=b,comparison=comparison)
        rows.append(row)
        (args.output/(date+"-metrics.json")).write_text(json.dumps(row,indent=2)+"\n")
        clips,keys=listening_pair(original,enhanced,metadata,rate,channels,listening)
        trials.extend(clips);answer_key.extend(keys)
        if args.keep_full_wav:
            run(["ffmpeg","-v","error","-y","-f","s16le","-ar",rate,"-ac",channels,"-i",enhanced,"-c:a","pcm_s16le",args.output/(date+"-enhanced.wav")])
        original.unlink();enhanced.unlink()
        print("RESULT",date,json.dumps(comparison["provisional_checks"]),flush=True)
        (args.output/(args.split+"-results.json")).write_text(json.dumps(dict(core_fingerprint=current,summary=summarize(rows),tracks=rows),indent=2)+"\n")
        (listening/"answer-key.json").write_text(json.dumps(answer_key,indent=2)+"\n")
        (listening/"trials.json").write_text(json.dumps(trials,indent=2)+"\n")
        make_page(listening,trials)
    if args.freeze:
        if args.split!="development" or len(rows)!=16:
            raise RuntimeError("Freeze requires all16 development tracks")
        frozen.write_text(json.dumps(dict(core_fingerprint=current,protocol_fingerprint=protocol_fingerprint(),development_summary=summarize(rows),holdout_policy="No threshold/parameter adjustment after this snapshot; any later changes invalidate confirmatory interpretation.",quality_claim="None; listener ratings pending."),indent=2)+"\n")
    print(json.dumps(summarize(rows),indent=2),flush=True)


if __name__=="__main__":
    main()
